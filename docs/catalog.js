// In-game cistern capacities, in the same units FWaterStorageComponent.m_WaterStored uses.
export const CISTERN_CAPACITY = {
  WaterCistern_Placeable: 5000,
  MediumWaterCistern_Placeable: 25000,
  LargeWaterCistern_Placeable: 100000
};

export function cisternCapacity(buildingType) {
  const name = String(buildingType || "");
  if (!/cistern/i.test(name)) return null;
  if (Object.prototype.hasOwnProperty.call(CISTERN_CAPACITY, name)) return CISTERN_CAPACITY[name];
  if (/large/i.test(name)) return CISTERN_CAPACITY.LargeWaterCistern_Placeable;
  if (/medium/i.test(name)) return CISTERN_CAPACITY.MediumWaterCistern_Placeable;
  return CISTERN_CAPACITY.WaterCistern_Placeable;
}

